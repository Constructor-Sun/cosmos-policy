#!/usr/bin/env python3
"""Phase 8 trajectory shift dynamics.

For each pairable (clean, perturb) HDF5 episode, this script follows the saved
rollout snapshots and computes

    delta_t = h_pert(t) - h_clean(t)

over the whole trajectory.  It reports temporal norm changes, directional
stability against the first nonzero shift, consecutive-step cosine, and a
trajectory-level PCA/SVD summary over the sequence of deltas.

The script is offline only: it reads ``manifest.parquet`` and HDF5 files
generated by ``collect_shift_embeddings.py`` and never loads the policy model.
"""

from __future__ import annotations

import argparse
import csv
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import h5py
import numpy as np
import pandas as pd

EPS = 1e-12
ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT_DIR = ROOT / "experiments/phase8_shift_embeddings/all_suites_full"
DEFAULT_OUTPUT_DIR = ROOT / "experiments/phase8_trajectory_shift_dynamics/all_suites_full"
DEFAULT_KS = [1, 2, 4, 8, 16]


@dataclass(frozen=True)
class Record:
    index: int
    suite: str
    task_name: str
    condition: str
    group: str
    clean_h5: Path
    pert_h5: Path
    clean_success: bool
    pert_success: bool
    clean_total_steps: int
    pert_total_steps: int
    clean_num_snapshots: int
    pert_num_snapshots: int
    save_interval: int
    variant_name: str


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input-dir", default=str(DEFAULT_INPUT_DIR))
    parser.add_argument("--output-dir", default=str(DEFAULT_OUTPUT_DIR))
    parser.add_argument("--layer", default="L27", choices=["L0", "L14", "L27"])
    parser.add_argument(
        "--space",
        default="hidden_video",
        choices=["hidden_video", "hidden_action", "hidden_video_action", "final_action"],
    )
    parser.add_argument("--ks", nargs="+", type=int, default=DEFAULT_KS)
    parser.add_argument(
        "--success-filter",
        choices=["clean-success", "all"],
        default="clean-success",
    )
    parser.add_argument(
        "--normalize-deltas-for-pca",
        action=argparse.BooleanOptionalAction,
        default=True,
        help="Normalize each timestep delta before trajectory PCA. Norm dynamics are always computed on raw deltas.",
    )
    parser.add_argument("--task", default=None, help="Optional exact task_name filter.")
    parser.add_argument("--condition", default=None, help="Optional exact condition filter.")
    parser.add_argument("--suite", default=None, help="Optional exact suite filter.")
    parser.add_argument("--max-records", type=int, default=0)
    return parser.parse_args()


def load_manifest(input_dir: Path) -> pd.DataFrame:
    manifest_path = input_dir / "manifest.parquet"
    if not manifest_path.exists():
        raise FileNotFoundError(f"manifest not found: {manifest_path}")
    return pd.read_parquet(manifest_path)


def make_records(df: pd.DataFrame, input_dir: Path, *, success_filter: str) -> list[Record]:
    clean_rows = {
        (str(row.suite), str(row.task_name)): row
        for row in df[df["condition"] == "clean"].itertuples(index=False)
    }
    records: list[Record] = []
    for row in df[df["condition"] != "clean"].itertuples(index=False):
        key = (str(row.suite), str(row.task_name))
        clean = clean_rows.get(key)
        if clean is None:
            continue
        clean_success = bool(clean.success)
        pert_success = bool(row.success)
        if success_filter == "clean-success" and not clean_success:
            continue
        if clean_success and pert_success:
            group = "preserved"
        elif clean_success and not pert_success:
            group = "flipped"
        else:
            group = "other"
        records.append(
            Record(
                index=len(records),
                suite=str(row.suite),
                task_name=str(row.task_name),
                condition=str(row.condition),
                group=group,
                clean_h5=input_dir / str(clean.h5_path),
                pert_h5=input_dir / str(row.h5_path),
                clean_success=clean_success,
                pert_success=pert_success,
                clean_total_steps=int(clean.total_steps),
                pert_total_steps=int(row.total_steps),
                clean_num_snapshots=int(clean.num_snapshots),
                pert_num_snapshots=int(row.num_snapshots),
                save_interval=int(row.save_interval),
                variant_name=str(row.variant_name),
            )
        )
    return records


def filter_records(records: list[Record], args: argparse.Namespace) -> list[Record]:
    out = []
    for record in records:
        if args.suite and record.suite != args.suite:
            continue
        if args.task and record.task_name != args.task:
            continue
        if args.condition and record.condition != args.condition:
            continue
        out.append(record)
    if args.max_records:
        out = out[: args.max_records]
    return out


def step_number(step_name: str) -> int:
    return int(step_name.split("_", 1)[1])


def shared_steps(clean_h5: Path, pert_h5: Path) -> list[str]:
    with h5py.File(clean_h5, "r") as clean, h5py.File(pert_h5, "r") as pert:
        clean_steps = set(clean["data"].keys())
        pert_steps = set(pert["data"].keys())
    return sorted(clean_steps & pert_steps, key=step_number)


def read_step(handle: h5py.File, step: str, *, layer: str, space: str) -> np.ndarray:
    key = "action" if space == "final_action" else layer
    data = handle[f"data/{step}/{key}"][()].astype(np.float32, copy=False)
    if space == "final_action":
        return data.reshape(-1)
    if data.shape != (3, 14, 14, 2048):
        raise ValueError(f"{layer} expected shape (3,14,14,2048), got {data.shape}")
    # CAPTURE_TEMPORAL_SLOTS = [2, 3, 4], saved as [wrist, primary, action].
    if space == "hidden_video":
        return data[:2].reshape(-1)
    if space == "hidden_action":
        return data[2].reshape(-1)
    if space == "hidden_video_action":
        return data.reshape(-1)
    raise ValueError(f"unknown space: {space}")


def effective_rank_at_energy(singular_values: np.ndarray, threshold: float) -> int | None:
    total = float(np.sum(singular_values**2))
    if total <= EPS:
        return None
    cumulative = np.cumsum(singular_values**2) / total
    return int(np.searchsorted(cumulative, threshold) + 1)


def explained_energy(singular_values: np.ndarray, k: int) -> float:
    total = float(np.sum(singular_values**2))
    if total <= EPS:
        return float("nan")
    kk = min(int(k), len(singular_values))
    return float(np.sum(singular_values[:kk] ** 2) / total)


def cosine(a: np.ndarray, b: np.ndarray) -> float:
    denom = float(np.linalg.norm(a) * np.linalg.norm(b))
    if denom <= EPS:
        return float("nan")
    return float(np.dot(a, b) / denom)


def trajectory_svd(X: np.ndarray, *, normalize_rows: bool) -> np.ndarray:
    row_norms = np.linalg.norm(X, axis=1)
    keep = row_norms > EPS
    if not np.any(keep):
        return np.asarray([], dtype=np.float64)
    Xnz = X[keep].astype(np.float64, copy=False)
    if normalize_rows:
        Xnz = Xnz / (row_norms[keep, None] + EPS)
    gram = Xnz @ Xnz.T
    evals = np.linalg.eigvalsh(gram)
    evals = np.maximum(evals[::-1], 0.0)
    return np.sqrt(evals)


def analyze_record(
    record: Record,
    *,
    layer: str,
    space: str,
    ks: list[int],
    normalize_deltas_for_pca: bool,
) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    steps = shared_steps(record.clean_h5, record.pert_h5)
    if not steps:
        raise RuntimeError(f"no shared steps for {record.clean_h5} and {record.pert_h5}")

    deltas = []
    step_rows = []
    with h5py.File(record.clean_h5, "r") as clean, h5py.File(record.pert_h5, "r") as pert:
        for step in steps:
            delta = read_step(pert, step, layer=layer, space=space) - read_step(clean, step, layer=layer, space=space)
            norm = float(np.linalg.norm(delta))
            deltas.append(delta.astype(np.float32, copy=False))
            step_rows.append(
                {
                    "record_index": record.index,
                    "suite": record.suite,
                    "task_name": record.task_name,
                    "condition": record.condition,
                    "group": record.group,
                    "layer": "action" if space == "final_action" else layer,
                    "space": space,
                    "step": step,
                    "step_idx": step_number(step),
                    "delta_norm": norm,
                    "is_zero": norm <= EPS,
                }
            )
    X = np.stack(deltas, axis=0)
    norms = np.asarray([row["delta_norm"] for row in step_rows], dtype=np.float64)
    nonzero = norms > EPS
    n_nonzero = int(np.sum(nonzero))
    n_zero = int(len(norms) - n_nonzero)

    first_nonzero_idx = int(np.argmax(nonzero)) if n_nonzero else -1
    first_vec = X[first_nonzero_idx] if n_nonzero else None
    prev_vec = None
    prev_nonzero = False
    cos_to_first = []
    consecutive_cos = []
    for i, row in enumerate(step_rows):
        if first_vec is not None and norms[i] > EPS:
            value = cosine(X[i], first_vec)
            row["cos_to_first_nonzero"] = value
            cos_to_first.append(value)
        else:
            row["cos_to_first_nonzero"] = float("nan")

        if prev_nonzero and norms[i] > EPS:
            value = cosine(X[i], prev_vec)
            row["cos_to_prev_nonzero"] = value
            consecutive_cos.append(value)
        else:
            row["cos_to_prev_nonzero"] = float("nan")
        if norms[i] > EPS:
            prev_vec = X[i]
            prev_nonzero = True

    S = trajectory_svd(X, normalize_rows=normalize_deltas_for_pca)
    summary: dict[str, Any] = {
        "record_index": record.index,
        "suite": record.suite,
        "task_name": record.task_name,
        "condition": record.condition,
        "group": record.group,
        "layer": "action" if space == "final_action" else layer,
        "space": space,
        "variant_name": record.variant_name,
        "clean_success": record.clean_success,
        "pert_success": record.pert_success,
        "clean_total_steps": record.clean_total_steps,
        "pert_total_steps": record.pert_total_steps,
        "clean_num_snapshots": record.clean_num_snapshots,
        "pert_num_snapshots": record.pert_num_snapshots,
        "n_shared_steps": len(steps),
        "n_nonzero_steps": n_nonzero,
        "n_zero_steps": n_zero,
        "first_step": steps[0],
        "last_shared_step": steps[-1],
        "first_nonzero_step": steps[first_nonzero_idx] if first_nonzero_idx >= 0 else "",
        "norm_start": float(norms[0]) if len(norms) else float("nan"),
        "norm_first_nonzero": float(norms[first_nonzero_idx]) if first_nonzero_idx >= 0 else float("nan"),
        "norm_end": float(norms[-1]) if len(norms) else float("nan"),
        "norm_mean": float(np.mean(norms)) if len(norms) else float("nan"),
        "norm_median": float(np.median(norms)) if len(norms) else float("nan"),
        "norm_max": float(np.max(norms)) if len(norms) else float("nan"),
        "norm_end_over_first_nonzero": float(norms[-1] / (norms[first_nonzero_idx] + EPS))
        if first_nonzero_idx >= 0
        else float("nan"),
        "norm_max_over_first_nonzero": float(np.max(norms) / (norms[first_nonzero_idx] + EPS))
        if first_nonzero_idx >= 0
        else float("nan"),
        "cos_to_first_mean": float(np.nanmean(cos_to_first)) if cos_to_first else float("nan"),
        "cos_to_first_min": float(np.nanmin(cos_to_first)) if cos_to_first else float("nan"),
        "cos_to_first_end": float(step_rows[-1]["cos_to_first_nonzero"]) if step_rows else float("nan"),
        "consecutive_cos_mean": float(np.nanmean(consecutive_cos)) if consecutive_cos else float("nan"),
        "consecutive_cos_min": float(np.nanmin(consecutive_cos)) if consecutive_cos else float("nan"),
        "traj_rank": int(np.sum(S > (float(S[0]) * 1e-10 if len(S) else EPS))) if len(S) else 0,
        "traj_r80": effective_rank_at_energy(S, 0.80),
        "traj_r90": effective_rank_at_energy(S, 0.90),
        "traj_r95": effective_rank_at_energy(S, 0.95),
    }
    for k in ks:
        summary[f"traj_ev_top{k}"] = explained_energy(S, k)
    return summary, step_rows


def write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        path.write_text("", encoding="utf-8")
        return
    fieldnames: list[str] = []
    for row in rows:
        for key in row:
            if key not in fieldnames:
                fieldnames.append(key)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def write_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2), encoding="utf-8")


def aggregate_condition(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    if not rows:
        return []
    df = pd.DataFrame(rows)
    metrics = [
        "n_shared_steps",
        "n_nonzero_steps",
        "n_zero_steps",
        "norm_end_over_first_nonzero",
        "norm_max_over_first_nonzero",
        "cos_to_first_mean",
        "cos_to_first_min",
        "cos_to_first_end",
        "consecutive_cos_mean",
        "consecutive_cos_min",
        "traj_r80",
        "traj_r90",
        "traj_r95",
        "traj_ev_top1",
        "traj_ev_top4",
        "traj_ev_top8",
        "traj_ev_top16",
    ]
    out = []
    for (condition, group), g in df.groupby(["condition", "group"], dropna=False):
        row: dict[str, Any] = {
            "condition": condition,
            "group": group,
            "n_trajectories": int(len(g)),
            "n_suites": int(g["suite"].nunique()),
            "n_tasks": int(g["task_name"].nunique()),
        }
        for metric in metrics:
            if metric not in g:
                continue
            values = pd.to_numeric(g[metric], errors="coerce")
            row[f"{metric}_mean"] = float(values.mean())
            row[f"{metric}_median"] = float(values.median())
        out.append(row)
    return out


def main() -> None:
    args = parse_args()
    input_dir = Path(args.input_dir).expanduser()
    if not input_dir.is_absolute():
        input_dir = input_dir.resolve()
    output_dir = Path(args.output_dir).expanduser()
    if not output_dir.is_absolute():
        output_dir = output_dir.resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    ks = sorted({int(k) for k in args.ks if int(k) > 0})
    df = load_manifest(input_dir)
    records = filter_records(make_records(df, input_dir, success_filter=args.success_filter), args)
    if not records:
        raise RuntimeError("no records after filtering")

    trajectory_rows: list[dict[str, Any]] = []
    step_rows_all: list[dict[str, Any]] = []
    errors: list[dict[str, Any]] = []

    print(f"[input] {input_dir}")
    print(f"[records] {len(records)}")
    print(f"[output] {output_dir}")
    for i, record in enumerate(records, start=1):
        if i % 25 == 0 or i == 1:
            print(f"[{i}/{len(records)}] {record.suite}/{record.condition}/{record.task_name}", flush=True)
        try:
            summary, step_rows = analyze_record(
                record,
                layer=args.layer,
                space=args.space,
                ks=ks,
                normalize_deltas_for_pca=args.normalize_deltas_for_pca,
            )
            trajectory_rows.append(summary)
            step_rows_all.extend(step_rows)
        except Exception as exc:
            errors.append(
                {
                    "record_index": record.index,
                    "suite": record.suite,
                    "task_name": record.task_name,
                    "condition": record.condition,
                    "error": str(exc),
                }
            )

    write_csv(output_dir / "trajectory_summary.csv", trajectory_rows)
    write_csv(output_dir / "step_dynamics.csv", step_rows_all)
    write_csv(output_dir / "condition_summary.csv", aggregate_condition(trajectory_rows))
    write_csv(output_dir / "errors.csv", errors)
    write_json(
        output_dir / "summary.json",
        {
            "input_dir": str(input_dir),
            "output_dir": str(output_dir),
            "layer": args.layer,
            "space": args.space,
            "ks": ks,
            "success_filter": args.success_filter,
            "normalize_deltas_for_pca": args.normalize_deltas_for_pca,
            "manifest_rows": int(len(df)),
            "records": len(records),
            "successful_trajectory_rows": len(trajectory_rows),
            "errors": len(errors),
            "outputs": {
                "trajectory_summary": str(output_dir / "trajectory_summary.csv"),
                "step_dynamics": str(output_dir / "step_dynamics.csv"),
                "condition_summary": str(output_dir / "condition_summary.csv"),
                "errors": str(output_dir / "errors.csv"),
            },
        },
    )
    print(f"[done] wrote {output_dir}", flush=True)


if __name__ == "__main__":
    main()
